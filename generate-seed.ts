/**
 * Regenerates supabase/seed.sql from lib/catalog-data.ts + lib/config.ts.
 * Usage:  node --experimental-strip-types scripts/generate-seed.ts > supabase/seed.sql
 */
import { SEED_CATEGORIES, SEED_FAQS, SEED_PACKAGES, SEED_PORTFOLIO, SEED_TESTIMONIALS } from '../lib/catalog-data.ts';
import { DEFAULT_CONTENT } from '../lib/config.ts';

const q = (v: string | null | undefined) => (v === null || v === undefined ? 'null' : `'${v.replace(/'/g, "''")}'`);
const arr = (items: string[]) => `array[${items.map(q).join(', ')}]::text[]`;
const out: string[] = [];

out.push(`-- ═══════════════════════════════════════════════════════════════════════
--  ABDUR RAHMAN DIGITAL STUDIO — starter content
--  Run AFTER schema.sql. Safe to re-run: it never overwrites your edits.
--  Prices are left empty on purpose — set them in Admin → Services / Packages.
--  (Generated by scripts/generate-seed.ts)
-- ═══════════════════════════════════════════════════════════════════════
`);

out.push('-- Service categories');
SEED_CATEGORIES.forEach((c, i) => {
  out.push(
    `insert into public.service_categories (slug, name, tagline, description, icon, sort_order) values (${q(c.slug)}, ${q(c.name)}, ${q(c.tagline)}, ${q(c.description)}, ${q(c.icon)}, ${i + 1}) on conflict (slug) do nothing;`,
  );
});

out.push('\n-- Services (starting_price NULL = "Price on request" until you set it)');
for (const c of SEED_CATEGORIES) {
  c.services.forEach((s, i) => {
    out.push(
      `insert into public.services (category_id, slug, name, short_description, description, icon, sort_order) select id, ${q(s.slug)}, ${q(s.name)}, ${q(s.short)}, ${q(s.description)}, ${q(s.icon)}, ${i + 1} from public.service_categories where slug = ${q(c.slug)} on conflict (slug) do nothing;`,
    );
  });
}

out.push('\n-- Pricing packages (price NULL until you set it)');
for (const p of SEED_PACKAGES) {
  out.push(
    `insert into public.packages (tier, name, tagline, price, features, delivery_time, revisions, is_featured, sort_order) values (${q(p.tier)}, ${q(p.name)}, ${q(p.tagline)}, null, ${arr(p.features)}, ${q(p.delivery_time)}, ${q(p.revisions)}, ${p.is_featured}, ${p.sort_order}) on conflict (tier) do nothing;`,
  );
}

out.push('\n-- Demo portfolio (clearly marked as demo; only inserted when the table is empty)');
out.push('insert into public.portfolio_items (title, category, description, is_demo, is_published, sort_order)\nselect * from (values');
out.push(
  SEED_PORTFOLIO.map((p) => `  (${q(p.title)}, ${q(p.category)}, ${q(p.description)}, true, true, ${p.sort_order})`).join(',\n'),
);
out.push(') as v(title, category, description, is_demo, is_published, sort_order)\nwhere not exists (select 1 from public.portfolio_items);');

out.push('\n-- Placeholder testimonials (replace with genuine reviews)');
out.push('insert into public.testimonials (name, role, quote, is_placeholder, is_published, sort_order)\nselect * from (values');
out.push(SEED_TESTIMONIALS.map((t) => `  (${q(t.name)}, ${q(t.role)}, ${q(t.quote)}, true, true, ${t.sort_order})`).join(',\n'));
out.push(') as v(name, role, quote, is_placeholder, is_published, sort_order)\nwhere not exists (select 1 from public.testimonials);');

out.push('\n-- FAQs');
out.push('insert into public.faqs (question, answer, sort_order, is_published)\nselect * from (values');
out.push(SEED_FAQS.map((f) => `  (${q(f.question)}, ${q(f.answer)}, ${f.sort_order}, true)`).join(',\n'));
out.push(') as v(question, answer, sort_order, is_published)\nwhere not exists (select 1 from public.faqs);');

out.push('\n-- Editable website text');
for (const [key, value] of Object.entries(DEFAULT_CONTENT)) {
  out.push(`insert into public.site_content (key, value) values (${q(key)}, ${q(value)}) on conflict (key) do nothing;`);
}

console.log(out.join('\n'));
